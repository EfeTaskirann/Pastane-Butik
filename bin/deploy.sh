#!/usr/bin/env bash
# ============================================================================
# bin/deploy.sh — Blue-Green Deployment Orchestrator
# ----------------------------------------------------------------------------
# Amaç:
#   `pastane` servisinin blue-green deploy adımlarını tek bir CLI'dan yönetir.
#   Canary trafik (%10 → %50 → %100) + < 30 sn rollback hedefi.
#
# Kullanım:
#   bin/deploy.sh deploy <slot> <image_tag>   # Slot'a yeni imajı yükle
#   bin/deploy.sh canary <percent>            # Green'e trafiğin yüzdesini aç
#   bin/deploy.sh promote <slot>              # Slot'u %100 live yap
#   bin/deploy.sh rollback                    # Acil: eski slot'a geri dön
#   bin/deploy.sh status                      # Mevcut upstream durumu
#   bin/deploy.sh health <slot>               # Slot healthcheck
#
# Ortam değişkenleri (opsiyonel):
#   NGINX_CONF       /etc/nginx/conf.d/pastane-upstream.conf
#   NGINX_BASELINE   /etc/nginx/conf.d/pastane-upstream.conf.baseline
#   LB_RELOAD_CMD    "sudo nginx -t && sudo nginx -s reload"
#   BLUE_HOST        pastane-blue
#   GREEN_HOST       pastane-green
#   HEALTH_URL       http://localhost/api/health/ready
#   HEALTH_TIMEOUT   60   (saniye)
#   DEPLOY_LOCK      /tmp/pastane-deploy.lock
#
# Exit codes:
#   0  başarı
#   1  argüman hatası
#   2  health check fail
#   3  nginx reload fail
#   4  lock alınamadı (concurrent deploy)
#   5  docker komut fail
#
# CLAUDE.md kuralları:
#   - Her fonksiyon hata yönetimi içermeli
#   - Placeholder veya TODO yasak
#   - Destructive komutlar için 5 sn iptal penceresi (Makefile pattern'i)
# ============================================================================

set -euo pipefail

# ─── Defaults ──────────────────────────────────────────────────────────────
NGINX_CONF="${NGINX_CONF:-/etc/nginx/conf.d/pastane-upstream.conf}"
NGINX_BASELINE="${NGINX_BASELINE:-/etc/nginx/conf.d/pastane-upstream.conf.baseline}"
LB_RELOAD_CMD="${LB_RELOAD_CMD:-sudo nginx -t && sudo nginx -s reload}"
BLUE_HOST="${BLUE_HOST:-pastane-blue}"
GREEN_HOST="${GREEN_HOST:-pastane-green}"
HEALTH_URL="${HEALTH_URL:-http://localhost/api/health/ready}"
HEALTH_TIMEOUT="${HEALTH_TIMEOUT:-60}"
DEPLOY_LOCK="${DEPLOY_LOCK:-/tmp/pastane-deploy.lock}"
LOG_FILE="${LOG_FILE:-/var/log/pastane-deploy.log}"

# ─── Utility ───────────────────────────────────────────────────────────────
log() {
    local msg="[$(date -u +%Y-%m-%dT%H:%M:%SZ)] $*"
    echo "$msg" | tee -a "$LOG_FILE"
}

die() {
    log "FATAL: $*"
    release_lock
    exit "${2:-1}"
}

acquire_lock() {
    if [[ -f "$DEPLOY_LOCK" ]]; then
        local pid
        pid="$(cat "$DEPLOY_LOCK" 2>/dev/null || echo 0)"
        if kill -0 "$pid" 2>/dev/null; then
            die "Başka bir deploy çalışıyor (pid=$pid). Bekleyin veya $DEPLOY_LOCK silin." 4
        else
            log "Stale lock bulundu (pid=$pid ölü), temizleniyor."
            rm -f "$DEPLOY_LOCK"
        fi
    fi
    echo $$ > "$DEPLOY_LOCK"
    trap release_lock EXIT
}

release_lock() {
    rm -f "$DEPLOY_LOCK" 2>/dev/null || true
}

confirm_destructive() {
    local prompt="${1:-Devam edilsin mi?}"
    if [[ "${ASSUME_YES:-0}" == "1" ]]; then
        log "ASSUME_YES=1 — onay atlandı."
        return 0
    fi
    log "$prompt  (5 sn içinde CTRL+C ile iptal)"
    sleep 5
}

# ─── Health check ──────────────────────────────────────────────────────────
health_check() {
    local slot="$1"
    local host
    case "$slot" in
        blue)  host="$BLUE_HOST"  ;;
        green) host="$GREEN_HOST" ;;
        *) die "Geçersiz slot: $slot (blue|green)" 1 ;;
    esac

    log "Healthcheck: $slot ($host) — timeout ${HEALTH_TIMEOUT}s"
    local elapsed=0
    local interval=2
    while [[ $elapsed -lt $HEALTH_TIMEOUT ]]; do
        local status_json
        status_json="$(curl -sf --max-time 5 "http://${host}${HEALTH_URL#http://localhost}" || echo '')"
        if [[ -n "$status_json" ]]; then
            if echo "$status_json" | grep -q '"status":"ok"'; then
                log "Healthcheck PASS: $slot"
                return 0
            fi
            if echo "$status_json" | grep -q '"status":"degraded"'; then
                log "Healthcheck DEGRADED (kabul edilebilir): $slot"
                return 0
            fi
        fi
        sleep $interval
        elapsed=$((elapsed + interval))
        log "  bekleniyor... (${elapsed}/${HEALTH_TIMEOUT}s)"
    done
    die "Healthcheck FAIL: $slot — ${HEALTH_TIMEOUT}s timeout" 2
}

# ─── Nginx upstream yönetimi ───────────────────────────────────────────────
render_upstream() {
    local blue_w="$1"
    local green_w="$2"

    cat <<EOF
# Auto-generated by bin/deploy.sh @ $(date -u +%Y-%m-%dT%H:%M:%SZ)
# blue_weight=$blue_w  green_weight=$green_w
upstream pastane_backend {
    server ${BLUE_HOST}:80  weight=${blue_w}  max_fails=3 fail_timeout=10s$([[ $blue_w -eq 0 ]] && echo ' backup' || true);
    server ${GREEN_HOST}:80 weight=${green_w} max_fails=3 fail_timeout=10s$([[ $green_w -eq 0 ]] && echo ' backup' || true);
    keepalive 32;
    keepalive_timeout 60s;
    keepalive_requests 1000;
}
EOF
}

apply_upstream() {
    local blue_w="$1"
    local green_w="$2"

    local tmp
    tmp="$(mktemp)"
    render_upstream "$blue_w" "$green_w" > "$tmp"

    log "Nginx upstream güncelleniyor: blue=${blue_w}% green=${green_w}%"

    if ! cp "$tmp" "$NGINX_CONF"; then
        rm -f "$tmp"
        die "Nginx conf yazılamadı: $NGINX_CONF" 3
    fi
    rm -f "$tmp"

    if ! bash -c "$LB_RELOAD_CMD"; then
        die "Nginx reload başarısız — eski config'e dön!" 3
    fi
    log "Nginx reload OK."
}

save_baseline() {
    # Baseline = 100% blue. Rollback hızı için hazırda tut.
    if [[ ! -f "$NGINX_BASELINE" ]]; then
        log "Baseline oluşturuluyor: $NGINX_BASELINE"
        render_upstream 100 0 > "$NGINX_BASELINE"
    fi
}

# ─── Komutlar ──────────────────────────────────────────────────────────────
cmd_deploy() {
    local slot="${1:-}"
    local tag="${2:-}"
    [[ -z "$slot" || -z "$tag" ]] && die "Kullanım: deploy <blue|green> <image_tag>" 1

    acquire_lock
    save_baseline

    local compose_file="docker-compose.${slot}.yml"
    [[ -f "$compose_file" ]] || die "Compose dosyası yok: $compose_file" 1

    log "DEPLOY: slot=$slot tag=$tag"

    # Tag'i env ile geçir
    export IMAGE_TAG="$tag"

    if ! docker compose -f "$compose_file" pull; then
        die "docker compose pull başarısız" 5
    fi

    if ! docker compose -f "$compose_file" up -d --no-deps app; then
        die "docker compose up başarısız" 5
    fi

    # Migration (expand pattern — backward compatible)
    log "Migration çalıştırılıyor: $slot"
    if ! docker compose -f "$compose_file" exec -T app php bin/migrate up; then
        die "Migration başarısız" 5
    fi

    health_check "$slot"

    log "DEPLOY OK: $slot → $tag (trafik YOK, canary için 'canary' komutunu çalıştır)"
}

cmd_canary() {
    local percent="${1:-}"
    [[ -z "$percent" ]] && die "Kullanım: canary <0-100>" 1
    [[ "$percent" =~ ^[0-9]+$ ]] || die "Yüzde sayı olmalı" 1
    (( percent >= 0 && percent <= 100 )) || die "Yüzde 0-100 aralığında olmalı" 1

    acquire_lock

    local blue_w=$((100 - percent))
    local green_w=$percent

    log "CANARY: green=${percent}%  (blue=${blue_w}%)"
    confirm_destructive "Trafik kayacak. Devam?"

    apply_upstream "$blue_w" "$green_w"
    log "CANARY APPLIED. Metrikleri izle (Sentry, Prometheus)."
    log "Rollback: bin/deploy.sh rollback"
}

cmd_promote() {
    local slot="${1:-}"
    [[ -z "$slot" ]] && die "Kullanım: promote <blue|green>" 1

    acquire_lock

    case "$slot" in
        blue)  apply_upstream 100 0 ;;
        green) apply_upstream 0 100 ;;
        *)     die "Geçersiz slot: $slot" 1 ;;
    esac

    log "PROMOTE: $slot → 100%"
    log "Eski slot 1 saat hot-standby tutulsun (izlemek için)."
}

cmd_rollback() {
    acquire_lock

    log "ROLLBACK başlatıldı!"

    if [[ -f "$NGINX_BASELINE" ]]; then
        log "Baseline'a dönüyor: $NGINX_BASELINE"
        cp "$NGINX_BASELINE" "$NGINX_CONF"
    else
        log "Baseline yok — manuel 100% blue yazılıyor"
        render_upstream 100 0 > "$NGINX_CONF"
    fi

    if ! bash -c "$LB_RELOAD_CMD"; then
        die "Nginx reload başarısız! ACİL: manuel müdahale!" 3
    fi

    log "ROLLBACK OK. Trafik blue'da."
    log "Green container'ı incele: docker compose -f docker-compose.green.yml logs --tail=200 app"
}

cmd_status() {
    log "─── Upstream Config ───"
    if [[ -f "$NGINX_CONF" ]]; then
        cat "$NGINX_CONF"
    else
        log "Nginx conf bulunamadı: $NGINX_CONF"
    fi

    log "─── Blue Health ───"
    curl -sf --max-time 5 "http://${BLUE_HOST}${HEALTH_URL#http://localhost}" | head -c 400 || log "  blue ERİŞİLEMİYOR"
    echo
    log "─── Green Health ───"
    curl -sf --max-time 5 "http://${GREEN_HOST}${HEALTH_URL#http://localhost}" | head -c 400 || log "  green ERİŞİLEMİYOR"
    echo
}

cmd_health() {
    local slot="${1:-}"
    [[ -z "$slot" ]] && die "Kullanım: health <blue|green>" 1
    health_check "$slot"
}

# ─── Dispatcher ────────────────────────────────────────────────────────────
main() {
    local action="${1:-}"
    shift || true

    case "$action" in
        deploy)   cmd_deploy   "$@" ;;
        canary)   cmd_canary   "$@" ;;
        promote)  cmd_promote  "$@" ;;
        rollback) cmd_rollback      ;;
        status)   cmd_status        ;;
        health)   cmd_health   "$@" ;;
        -h|--help|help|"")
            cat <<EOF
bin/deploy.sh — Blue-Green Deployment Orchestrator

Komutlar:
  deploy <blue|green> <image_tag>   Slot'a yeni imajı yükle + migrate + health
  canary <0-100>                    Green'e trafik yüzdesini aç (blue otomatik tamamlayıcı)
  promote <blue|green>              Slot'u %100 live yap
  rollback                          Baseline'a dön (< 30 sn hedef)
  status                            Upstream + her iki slot health özeti
  health <blue|green>               Sadece sağlık kontrolü

Ortam değişkenleri:
  NGINX_CONF, NGINX_BASELINE, LB_RELOAD_CMD, BLUE_HOST, GREEN_HOST,
  HEALTH_URL, HEALTH_TIMEOUT, ASSUME_YES=1 (onay atla)
EOF
            exit 0
            ;;
        *) die "Bilinmeyen komut: $action (help için -h)" 1 ;;
    esac
}

main "$@"
